# Корни слов → ответ. Точное совпадение по ключам FAQ ловит далеко не всё:
# «а по срокам как?» не содержит слова «сроки», «сколько везти» — слова
# «доставка». Ищем по корням, чтобы бот отвечал сам, а не звал менеджера.
FAQ_STEMS = (
    (("доставк", "привез", "привоз", "отправ", "почтой", "курьер", "самовывоз",
      "везти", "везёт", "везет", "пересыл"), "доставка"),
    (("оплат", "оплач", "заплат", "платит", "картой", "сбп", "перевод",
      "рассрочк", "чек", "счёт", "счет"), "оплата"),
    (("гарант", "возврат", "вернуть", "брак", "не понравит", "обмен",
      "если не подойд"), "гарантия"),
    (("срок", "быстро", "долго", "успе", "когда будет", "когда готов",
      "сколько ждать", "сколько делает", "как скоро"), "сроки"),
    (("дорого", "дешевле", "скидк", "цена высок", "много стоит"), "дорого"),
    (("подума", "сомнева", "не уверен", "боюсь", "а вдруг"), "подумаю"),
    (("как выглядит", "фото готов", "пример работ", "образец", "покажите"),
     "как выглядит"),
)


def find_faq(text: str) -> str:
    """Ищет готовый ответ: сначала по точным ключам, потом по корням."""
    lowered = (text or "").lower()
    for keyword, answer in FAQ.items():
        if keyword in lowered:
            return answer
    for stems, key in FAQ_STEMS:
        if any(stem in lowered for stem in stems):
            return FAQ.get(key, "")
    return ""

